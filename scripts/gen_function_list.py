"""Regenerate docs/FUNCTIONS.md from the built-in registry.

Usage: python scripts/gen_function_list.py
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from mylab.builtins import BUILTINS

SECTIONS = {
    "core": "Arrays, sizes, types and conversions",
    "mathfns": "Math, reductions, sorting and sets",
    "linalg": "Linear algebra",
    "strings": "Text and formatting",
    "data": "Cell arrays, structs and functional tools",
    "system": "Output, errors, workspace, files and timing",
    "numerics": "Polynomials, interpolation, optimization, integration and ODEs",
    "plotting": "Plotting",
    "table": "Tables",
    "signal": "Signal processing",
    "stats": "Statistics and probability",
    "optim": "Optimization",
    "extras": "More core functions",
    "io": "Text-file input and output, folders",
    "langextras": "Input parsing, cleanup, random streams, timers and environment",
    "events": "Class events and enumerations",
    "categorical": "Categorical arrays",
    "spatial": "Geometry and scattered-data interpolation",
    "ndmath": "N-dimensional transforms, sampling and more statistics",
    "jsonfuncs": "JSON",
    "audio": "Audio files",
    "excel": "Excel files",
    "plotmore": "More plot types",
}


def main() -> None:
    groups: dict[str, list[str]] = defaultdict(list)
    for name, fn in BUILTINS.items():
        module = fn.__module__.rsplit(".", 1)[-1]
        groups[module].append(name)
    lines = [
        "# Built-in functions",
        "",
        f"mylab currently provides **{len(BUILTINS)}** built-in functions. "
        "Behaviour follows the documented MATLAB semantics where implemented; "
        "see [COMPATIBILITY.md](COMPATIBILITY.md) for known differences.",
        "",
        "_This file is generated by `scripts/gen_function_list.py` - do not edit by hand._",
        "",
    ]
    sections = dict(SECTIONS)
    for module in sorted(groups):
        sections.setdefault(module, module.replace("_", " ").capitalize())
    for module, title in sections.items():
        names = sorted(groups.get(module, []), key=str.lower)
        if not names:
            continue
        lines += [f"## {title}", "", ", ".join(f"`{n}`" for n in names), ""]
    out = Path(__file__).resolve().parent.parent / "docs" / "FUNCTIONS.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({len(BUILTINS)} functions)")


if __name__ == "__main__":
    main()
