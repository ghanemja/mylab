"""Regenerate the data files the diagram editor is built from.

Writes
  web/js/blocks/catalog.js    the block library (from mylab.blocks.library)
  web/js/blocks/examples.js   the example models (from examples/blocks/*.mlb.json)
and refreshes the block table in docs/BLOCKS.md (between the BLOCK-TABLE markers).

Usage: python scripts/gen_blocks_data.py [--check]
With --check nothing is written; the exit code is 1 when a file is out of date.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from mylab.blocks.library import catalog

ROOT = Path(__file__).resolve().parent.parent
HEADER = "// Generated by scripts/gen_blocks_data.py. Do not edit by hand.\n"
TITLES = {
    "mass_spring_damper": "Mass, spring and damper", "pid_speed_control": "PID speed control",
    "bouncing_ball": "Bouncing ball", "thermostat": "Thermostat with a relay",
    "sampled_data_control": "Sampled-data control", "van_der_pol": "Van der Pol oscillator",
}


def catalog_js() -> str:
    return HEADER + "export const CATALOG = " + json.dumps(catalog(), indent=1, ensure_ascii=False) + ";\n"


def examples_js() -> str:
    items = []
    for name, title in TITLES.items():
        text = (ROOT / "examples" / "blocks" / f"{name}.mlb.json").read_text(encoding="utf-8")
        data = json.loads(text)
        items.append({"name": name, "file": f"{name}.mlb.json", "title": title, "description": data.get("description", ""),
                      "text": text})
    return HEADER + "export const BLOCK_EXAMPLES = " + json.dumps(items, indent=1, ensure_ascii=False) + ";\n"


def block_table() -> str:
    cat = catalog()
    lines = []
    for c in cat["categories"]:
        lines += [f"**{c}**", "", "| Block | Type name | What it does |", "|-------|-----------|--------------|"]
        for b in cat["blocks"]:
            if b["category"] == c:
                lines.append(f"| {b['title']} | `{b['type']}` | {b['doc']} |")
        lines.append("")
    return "\n".join(lines)


def docs_md(current: str) -> str:
    start, end = "<!-- BLOCK-TABLE:START -->", "<!-- BLOCK-TABLE:END -->"
    if start not in current or end not in current:
        return current
    head, rest = current.split(start, 1)
    _, tail = rest.split(end, 1)
    n = len(catalog()["blocks"])
    return f"{head}{start}\n\n{n} blocks.\n\n{block_table()}{end}{tail}"


def main() -> int:
    check = "--check" in sys.argv
    targets = {
        ROOT / "web" / "js" / "blocks" / "catalog.js": catalog_js(),
        ROOT / "web" / "js" / "blocks" / "examples.js": examples_js(),
    }
    docs = ROOT / "docs" / "BLOCKS.md"
    if docs.exists():
        targets[docs] = docs_md(docs.read_text(encoding="utf-8"))
    stale = 0
    for path, text in targets.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale += 1
            if check:
                print(f"out of date: {path.relative_to(ROOT)}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
                print(f"wrote {path.relative_to(ROOT)}")
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
