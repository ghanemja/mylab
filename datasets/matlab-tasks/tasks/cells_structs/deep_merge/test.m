a = struct('name', 'app', 'opts', struct('depth', 2, 'color', 'red'));
b = struct('opts', struct('color', 'blue', 'width', 5), 'version', 3);
c = deep_merge(a, b);
assert(isequal(fieldnames(c), {'name'; 'opts'; 'version'}), 'top-level order');
assert(strcmp(c.name, 'app') && c.version == 3, 'single-side fields');
assert(isequal(fieldnames(c.opts), {'depth'; 'color'; 'width'}), 'nested order');
assert(c.opts.depth == 2 && strcmp(c.opts.color, 'blue') && c.opts.width == 5, 'nested values');
a = struct('x', struct('y', struct('z', 1, 'w', 2)));
b = struct('x', struct('y', struct('z', 10)));
c = deep_merge(a, b);
assert(c.x.y.z == 10 && c.x.y.w == 2, 'three levels');
c = deep_merge(struct('p', struct('q', 1)), struct('p', 5));
assert(isequal(c.p, 5), 'number replaces struct');
c = deep_merge(struct('p', 5), struct('p', struct('q', 1)));
assert(isstruct(c.p) && c.p.q == 1, 'struct replaces number');
arr = struct('k', {1, 2});
c = deep_merge(struct('s', struct('k', 0, 'm', 9)), struct('s', arr));
assert(isequal(size(c.s), [1 2]) && ~isfield(c.s, 'm'), 'struct array replaces');
c = deep_merge(struct(), struct('only', {{1, 2}}));
assert(isequal(fieldnames(c), {'only'}) && isequal(c.only, {1, 2}), 'empty left side, cell value');
c = deep_merge(struct('keep', 'me'), struct());
assert(isequal(c, struct('keep', 'me')), 'empty right side');
