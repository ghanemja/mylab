assert(g == 1 && p == 2 && q == 3, 'two primes');
[g, p, q] = largest_prime_gap(2);
assert(g == 0 && isnan(p) && isnan(q), 'single prime');
[g, p, q] = largest_prime_gap(1);
assert(g == 0 && isnan(p) && isnan(q), 'no primes');
