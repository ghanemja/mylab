assert(isempty(r) && isequal(size(r), [1 0]), 'only complex roots');
r = real_roots_in(conv([1 -2 1], [1 0 4]), -5, 5);
assert(numel(r) == 1 && abs(r - 1) < 1e-6, 'double root reported once, complex pair dropped');
